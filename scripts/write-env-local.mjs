/**
 * Writes .env.local from `npx supabase status -o env` for local integration.
 * Never commits .env.local. Run after: npx supabase start && npx supabase db reset
 */

import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { spawnSync } from 'node:child_process'

const result = spawnSync('npx', ['supabase', 'status', '-o', 'env'], {
  encoding: 'utf8',
  shell: true,
  cwd: process.cwd(),
})

if (result.status !== 0) {
  console.error(result.stderr || result.stdout)
  console.error('Is local Supabase running? Try: npm run supabase:start')
  process.exit(1)
}

const envText = result.stdout
const map = new Map()
for (const raw of envText.split(/\r?\n/)) {
  const line = raw.trim()
  if (!line || line.startsWith('#')) continue
  const eq = line.indexOf('=')
  if (eq <= 0) continue
  const key = line.slice(0, eq).trim()
  let value = line.slice(eq + 1).trim()
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    value = value.slice(1, -1)
  }
  // supabase status -o env uses API_URL, ANON_KEY, SERVICE_ROLE_KEY, etc.
  map.set(key, value)
}

const apiUrl = map.get('API_URL') ?? map.get('SUPABASE_URL') ?? 'http://127.0.0.1:54321'
const anon = map.get('ANON_KEY') ?? map.get('SUPABASE_ANON_KEY')
const service = map.get('SERVICE_ROLE_KEY') ?? map.get('SUPABASE_SERVICE_ROLE_KEY')

if (!anon || !service) {
  console.error('Could not parse anon/service keys from supabase status -o env')
  console.error(envText)
  process.exit(1)
}

const contents = `# Generated by scripts/write-env-local.mjs — DO NOT COMMIT
VITE_SUPABASE_URL=${apiUrl}
VITE_SUPABASE_ANON_KEY=${anon}
SUPABASE_URL=${apiUrl}
SUPABASE_ANON_KEY=${anon}
SUPABASE_SERVICE_ROLE_KEY=${service}
SUPABASE_INTEGRATION=1
`

const out = resolve(process.cwd(), '.env.local')
writeFileSync(out, contents, 'utf8')
console.log(`Wrote ${out}`)
console.log('Integration tests enabled (SUPABASE_INTEGRATION=1)')
